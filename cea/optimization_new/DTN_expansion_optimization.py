        cluster0_key = '0'
        if cluster0_key in self.cluster_metrics:
            metrics = self.cluster_metrics[cluster0_key]
            annual_demand = metrics.get(f'total_annual_{demand_type}_MWh', 0)
            pipe_length = metrics.get('total_pipe_length_m', 0)

