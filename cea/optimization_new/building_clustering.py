def read_automatic_dtn(locator, network_type='DH'):
    """
    Option 1: Automatically identify existing DTN buildings using the nodes shapefile
    generated by the Thermal Network Part 1: Layout.

    The nodes shapefiles have a column named "building" where non-"NONE" values indicate
    buildings in the existing DTN.

    Parameters:
    -----------
    locator : InputLocator
        CEA InputLocator object
    network_type : str
        'DH' for district heating or 'DC' for district cooling

    Returns:
    --------
    list
        List of building IDs in the existing DTN
    """
    nodes_shp_path = locator.get_network_layout_nodes_shapefile(network_type, "")

    if not os.path.exists(nodes_shp_path):
        print(f"Warning: No existing DTN found at {nodes_shp_path}")
        return []

    nodes_shp = gpd.read_file(nodes_shp_path)

    # Filter nodes where the 'building' field is not "NONE"
    dtn_buildings = nodes_shp[nodes_shp['building'] != "NONE"]['building'].unique().tolist()

    # Return as a list of strings (ensure type)
    return [str(b) for b in dtn_buildings if b is not None]


def read_manual_dtn(existing_dtn_filepath):
    """
    Option 2: Reads a user-defined CSV file that lists IDs of buildings connected to existing DTN.

    Parameters:
    -----------
    existing_dtn_filepath : str
        Path to CSV file with building IDs

    Returns:
    --------
    list
        List of building IDs in the existing DTN
    """
    if existing_dtn_filepath and os.path.exists(existing_dtn_filepath):
        dtn_df = pd.read_csv(existing_dtn_filepath)
        return dtn_df['name'].tolist()
    else:
        return []


def merge_building_data(buildings_shp, demand_df):
    """
    Merge building spatial data (from zone shapefile) with demand data (from Total_demand.csv).
    - Makes sure both inputs have the "name" field as string
    - Calculates each building's centroid and extracts the x and y coordinates

    Parameters:
    -----------
    buildings_shp : GeoDataFrame
        Building geometries from the zone shapefile
    demand_df : DataFrame
        Building energy demand from Total_demand.csv

    Returns:
    --------
    GeoDataFrame
        A merged DataFrame containing building footprints, demand data, and centroid coordinates
    """
    # Convert name fields to string for consistent joining
    buildings_shp['name'] = buildings_shp['name'].astype(str)
    demand_df['name'] = demand_df['name'].astype(str)

    # Merge on building name
    merged_df = buildings_shp.merge(demand_df, on='name', how='inner')

    # Calculate centroid coordinates for each building
    centroids = merged_df.geometry.centroid
    merged_df['x'] = centroids.x
    merged_df['y'] = centroids.y

    return merged_df


def process_archetypes(buildings_df):
    """
    Process building archetypes from CEA-4 use_type format with mixed-use buildings support.

    Parameters:
    -----------
    buildings_df : GeoDataFrame
        Building data with use_type1, use_type2, use_type3 columns

    Returns:
    --------
    GeoDataFrame
        DataFrame with processed archetype information
    """
    df = buildings_df.copy()

    # Create a dominant use field based on use_type1
    df['dominant_use'] = df['use_type1']

    # Flag mixed-use buildings (those with a non-zero secondary use type)
    mixed_use_mask = (df['use_type2'].notna()) & (df['use_type2r'] > 0)
    df['is_mixed_use'] = False
    df.loc[mixed_use_mask, 'is_mixed_use'] = True

    # Create numerical representations for each use type
    # First collect all unique use types
    use_types = set()
    for i in range(1, 4):
        type_col = f'use_type{i}'
        ratio_col = f'use_type{i}r'

        # Add to use types if present with non-zero ratio
        if type_col in df.columns and ratio_col in df.columns:
            for use_type, ratio in zip(df[type_col], df[ratio_col]):
                if use_type and not pd.isna(use_type) and ratio > 0:
                    use_types.add(use_type)

    # Now create columns for each use type with their ratio values
    for use_type in use_types:
        df[f'use_{use_type}'] = 0.0

        # Fill in values from each use_type column
        for i in range(1, 4):
            type_col = f'use_type{i}'
            ratio_col = f'use_type{i}r'

            if type_col in df.columns and ratio_col in df.columns:
                # Where this use type matches, set the ratio
                match_mask = (df[type_col] == use_type) & (df[ratio_col] > 0)
                df.loc[match_mask, f'use_{use_type}'] = df.loc[match_mask, ratio_col]

    return df


def prepare_features(merged_df, heat_col='QH_sys_MWhyr', spatial_weight=2.0, archetype_weight=0.8):
    """
    Prepares the feature matrix for clustering with adjustable feature weighting.

    Parameters:
    -----------
    merged_df : DataFrame
        The merged dataframe with building information
    heat_col : str
        The column name for heat demand
    spatial_weight : float
        Weight multiplier for spatial coordinates (higher values emphasize spatial proximity)
    archetype_weight : float
        Weight multiplier for building archetype features

    Returns:
    --------
    scaled_features : ndarray
        Normalized features array
    scaler : StandardScaler
        The scaler object used for normalization
    """
    # Ensure heat demand is in kWh (since the columns are in MWh in the CEA outputs)
    merged_df['heat_kWhyr'] = merged_df[heat_col] * 1000

    # Create initial numeric features array with heat demand and coordinates
    numeric_features = merged_df[['heat_kWhyr', 'x', 'y']].copy()

    # Normalize numeric features
    scaler = StandardScaler()
    scaled_features = scaler.fit_transform(numeric_features)

    # Apply weights to spatial coordinates
    scaled_features[:, 1] *= spatial_weight  # x coordinate
    scaled_features[:, 2] *= spatial_weight  # y coordinate

    # Get archetype features (columns starting with 'use_')
    use_cols = [col for col in merged_df.columns if col.startswith('use_') and
                col not in ['use_type1', 'use_type2', 'use_type3',
                            'use_type1r', 'use_type2r', 'use_type3r']]

    # If archetype features exist, include them in clustering
    if use_cols:
        archetype_features = merged_df[use_cols].values

        # Normalize archetype features
        if np.any(archetype_features):  # Only if there are non-zero values
            archetype_scaler = StandardScaler()
            scaled_archetype_features = archetype_scaler.fit_transform(archetype_features)

            # Apply weight to archetype features
            scaled_archetype_features *= archetype_weight

            # Combine numeric and archetype features
            scaled_features = np.hstack((scaled_features, scaled_archetype_features))

    return scaled_features, scaler


def perform_clustering(scaled_features, n_clusters, min_buildings_per_cluster=5):
    """
    Runs KMeans clustering with minimum cluster size constraint.

    Parameters:
    -----------
    scaled_features : ndarray
        The normalized feature array
    n_clusters : int
        Initial number of clusters to create
    min_buildings_per_cluster : int
        Minimum number of buildings per cluster

    Returns:
    --------
    labels : ndarray
        Cluster labels for each building
    kmeans : KMeans
        The fitted KMeans model
    """
    # Calculate maximum clusters based on data size and minimum buildings per cluster
    max_possible_clusters = max(2, min(n_clusters, len(scaled_features) // min_buildings_per_cluster))

    # Ensure we don't try to create more clusters than data points
    n_clusters = min(max_possible_clusters, len(scaled_features))

    # Run KMeans clustering
    kmeans = KMeans(n_clusters=n_clusters, random_state=42, n_init=10)
    kmeans.fit(scaled_features)
    labels = kmeans.labels_

    # Check if any cluster is too small
    unique_labels, counts = np.unique(labels, return_counts=True)
    too_small = counts < min_buildings_per_cluster

    # If some clusters are too small, try fewer clusters
    if np.any(too_small) and n_clusters > 2:
        print(f"Some clusters are too small. Reducing clusters from {n_clusters} to {n_clusters - 1}.")
        return perform_clustering(scaled_features, n_clusters - 1, min_buildings_per_cluster)

    return labels, kmeans


def save_results(cluster_data, locator):
    """
    Save clustering results to the project outputs directory.
    Only saves essential columns for further analysis.

    Parameters:
    ----------
    cluster_data : DataFrame
        Data containing building IDs and their assigned clusters
    locator : InputLocator
        CEA InputLocator object

    Returns:
    -------
    tuple
        Paths to the saved CSV and shapefile
    """
    # Get scenario path from locator
    scenario_path = locator.scenario

    # Define the output directory
    output_dir = os.path.join(scenario_path, 'outputs', 'data', 'optimization')

    # Create directory if it doesn't exist
    os.makedirs(output_dir, exist_ok=True)

    # Define output paths
    csv_path = os.path.join(output_dir, 'building_clusters.csv')
    shp_path = os.path.join(output_dir, 'building_clusters.shp')

    # Select only required columns
    columns_to_keep = ['name', 'x', 'y', 'in_existing_DTN', 'cluster', 'heat_kWhyr']

    # Add use type columns if they exist
    use_cols = [col for col in cluster_data.columns if col.startswith('use_') and
                col not in ['use_type1', 'use_type2', 'use_type3',
                            'use_type1r', 'use_type2r', 'use_type3r']]
    columns_to_keep.extend(use_cols)

    # Add dominant use if it exists
    if 'dominant_use' in cluster_data.columns:
        columns_to_keep.append('dominant_use')

    # Add geometry for shapefile
    if isinstance(cluster_data, gpd.GeoDataFrame):
        columns_to_keep.append('geometry')

    save_data = cluster_data[columns_to_keep].copy()

    # Save CSV without the geometry column
    if 'geometry' in save_data.columns:
        save_data.drop(columns=['geometry']).to_csv(csv_path, index=False)
    else:
        save_data.to_csv(csv_path, index=False)

    # Save as shapefile
    if isinstance(cluster_data, gpd.GeoDataFrame):
        save_data.to_file(shp_path)

    print(f"Results saved to {output_dir}")
    return csv_path, shp_path


def save_cluster_centroids(cluster_data, locator):
    """
    Create and save centroid points for each cluster.
    Centroids represent the geographic center of buildings in each cluster,
    along with aggregate statistics.

    Parameters:
    ----------
    cluster_data : GeoDataFrame
        Data containing building geometries and cluster assignments
    locator : InputLocator
        CEA InputLocator object

    Returns:
    -------
    str
        Path to the saved centroid shapefile
    """
    # Get scenario path from locator
    scenario_path = locator.scenario

    # Define the output directory and path
    output_dir = os.path.join(scenario_path, 'outputs', 'data', 'optimization')
    os.makedirs(output_dir, exist_ok=True)
    centroid_shp_path = os.path.join(output_dir, 'cluster_centroids.shp')

    # Group by cluster and calculate centroids
    cluster_centroids = []
    for cluster_num, group in cluster_data.groupby('cluster'):
        # Calculate the mean position of all buildings in this cluster
        mean_x = group['x'].mean()
        mean_y = group['y'].mean()

        # Calculate total and average attributes for the cluster
        total_heat = group['heat_kWhyr'].sum()
        avg_heat = group['heat_kWhyr'].mean()

        # Get the most common building use if available
        dominant_use = "unknown"
        if 'dominant_use' in group.columns:
            use_counts = Counter(group['dominant_use'].dropna())
            if use_counts:
                dominant_use = use_counts.most_common(1)[0][0]

        # Create a Point geometry for this cluster centroid
        centroid_geom = Point(mean_x, mean_y)

        # Add to the list
        cluster_centroids.append({
            'cluster': int(cluster_num),
            'n_buildings': len(group),
            'total_heat_kWh': total_heat,
            'avg_heat_kWh': avg_heat,
            'archetype': dominant_use,
            'x': mean_x,
            'y': mean_y,
            'geometry': centroid_geom
        })

    # Create a GeoDataFrame from the centroids list
    centroids_gdf = gpd.GeoDataFrame(cluster_centroids, crs=cluster_data.crs)

    # Save as shapefile
    centroids_gdf.to_file(centroid_shp_path)
    print(f"Cluster centroids saved to: {centroid_shp_path}")

    return centroid_shp_path


def visualize_clusters(merged_df):
    """
    Visualizes the clustered buildings using a scatter plot with discrete colors.

    Parameters:
    -----------
    merged_df : DataFrame
        The dataframe with cluster assignments
    """
    # Get unique cluster numbers
    clusters = sorted(merged_df['cluster'].unique())
    n_clusters = len(clusters)

    # Choose a discrete colormap based on number of clusters
    if n_clusters <= 10:
        # For small number of clusters, use a qualitative colormap
        colors = plt.cm.tab10.colors[:n_clusters]
    else:
        # For more clusters, use a larger discrete colormap
        colors = plt.cm.tab20.colors[:n_clusters]

    # Create a custom colormap
    cmap = ListedColormap(colors)

    # Create a scatter plot
    plt.figure(figsize=(12, 9))

    # Plot each cluster with a discrete color
    for i, cluster in enumerate(clusters):
        cluster_data = merged_df[merged_df['cluster'] == cluster]
        plt.scatter(cluster_data['x'], cluster_data['y'],
                    color=colors[i], s=100, edgecolor='k', alpha=0.7,
                    label=f'Cluster {cluster} ({len(cluster_data)} bldgs)')

    # Add labels and title
    plt.xlabel('X Coordinate', fontsize=12)
    plt.ylabel('Y Coordinate', fontsize=12)
    plt.title('Building Clusters based on Heat Demand and Proximity', fontsize=14)

    # Add a legend
    plt.legend(title='Clusters', loc='best', bbox_to_anchor=(1.05, 1), borderaxespad=0., fontsize=10)

    # Make layout tight to accommodate legend
    plt.tight_layout()

    # Show plot
    plt.show()


def cluster_buildings(buildings_shp, demand_df, locator,
                      dtn_method='automatic',
                      existing_dtn_filepath=None,
                      extra_clusters=2,
                      network_type='DH',
                      spatial_weight=2.0,
                      archetype_weight=0.8,
                      min_buildings_per_cluster=5):
    """
    Main clustering function.

    Parameters:
    -----------
    buildings_shp : GeoDataFrame
        Building footprints from shapefile
    demand_df : DataFrame
        Building demand data
    locator : InputLocator
        CEA InputLocator object
    dtn_method : str
        Method to identify existing DTN buildings ('automatic' or 'manual')
    existing_dtn_filepath : str
        Path to CSV file for manual DTN selection
    extra_clusters : int
        Number of clusters for non-DTN buildings
    network_type : str
        'DH' for district heating or 'DC' for district cooling
    spatial_weight : float
        Weight multiplier for spatial coordinates
    archetype_weight : float
        Weight multiplier for building archetypes
    min_buildings_per_cluster : int
        Minimum number of buildings per cluster
    """
    # Process archetypes in the building data
    buildings_shp = process_archetypes(buildings_shp)

    # Merge spatial data and demand data
    merged_df = merge_building_data(buildings_shp, demand_df)

    # Identify DTN buildings
    if dtn_method == 'automatic':
        dtn_buildings = read_automatic_dtn(locator, network_type)
    elif dtn_method == 'manual':
        dtn_buildings = read_manual_dtn(existing_dtn_filepath)
    else:
        dtn_buildings = []

    print(f"Identified {len(dtn_buildings)} buildings in existing DTN")

    # Add a flag to mark DTN buildings
    merged_df['in_existing_DTN'] = merged_df['name'].isin(dtn_buildings)

    # Separate DTN and non-DTN buildings
    dtn_df = merged_df[merged_df['in_existing_DTN']].copy()
    non_dtn_df = merged_df[~merged_df['in_existing_DTN']].copy()

    # For non-DTN buildings, prepare features and perform clustering
    scaled_features, scaler = prepare_features(
        non_dtn_df,
        heat_col='QH_sys_MWhyr',
        spatial_weight=spatial_weight,
        archetype_weight=archetype_weight
    )

    # Ensure minimum number of clusters
    extra_clusters = max(2, extra_clusters)

    # Perform clustering
    labels, kmeans = perform_clustering(scaled_features, n_clusters=extra_clusters,
                                        min_buildings_per_cluster=min_buildings_per_cluster)

    # Assign cluster labels to non-DTN buildings (shift labels to start from 1)
    non_dtn_df['cluster'] = labels + 1  # Shift labels so that DTN becomes cluster 0

    # For DTN buildings, assign a cluster label of 0
    if not dtn_df.empty:
        dtn_df['cluster'] = 0
        final_df = pd.concat([dtn_df, non_dtn_df], ignore_index=True)
    else:
        final_df = non_dtn_df

    # Save results and cluster centroids
    out_csv, out_shp = save_results(final_df, locator)
    centroid_shp = save_cluster_centroids(final_df, locator)

    print(f"Results saved to:")
    print(f"  - Building clusters CSV: {out_csv}")
    print(f"  - Building clusters shapefile: {out_shp}")
    print(f"  - Cluster centroids shapefile: {centroid_shp}")

    # Visualize clusters
    visualize_clusters(final_df)

    return final_df


def main(config):
    """
    Main function to run the building clustering.

    Args:
        config: Configuration object with all parameters
    """
    # Get parameters from config
    scenario = config.scenario
    extra_clusters = config.building_clustering.extra_clusters
    dtn_method = config.building_clustering.dtn_method
    existing_dtn_filepath = config.building_clustering.existing_dtn_filepath
    network_type = config.building_clustering.network_type

    # Additional parameters with default values
    spatial_weight = 2.0  # Weight for spatial coordinates
    archetype_weight = 0.8  # Weight for building archetypes
    min_buildings_per_cluster = 5  # Minimum buildings per cluster

    # Setup locator and load data
    locator = cea.inputlocator.InputLocator(scenario=scenario)
    buildings_shp = gpd.read_file(locator.get_zone_geometry())
    demand_df = pd.read_csv(locator.get_total_demand())

    # Check if extra_clusters is empty string or None and set default
    if not extra_clusters:
        extra_clusters = 2

    # Call the cluster_buildings function with parameters from config
    cluster_buildings(
        buildings_shp, demand_df, locator,
        dtn_method=dtn_method,
        existing_dtn_filepath=existing_dtn_filepath,
        extra_clusters=extra_clusters,
        network_type=network_type,
        spatial_weight=spatial_weight,
        archetype_weight=archetype_weight,
        min_buildings_per_cluster=min_buildings_per_cluster
    )


